"""Import the app's selected Uicons from Flaticon's official npm distribution.

Run with tooling Python + fonttools[woff] (4.68.0 used here). The npm archive
contains webfonts; export their original glyph outlines as local SVG assets.
No tracing, redraw, CDN dependency, or entire icon library in the app bundle.
"""
import base64
import hashlib
import io
import json
import re
import tarfile
from pathlib import Path
from urllib.request import urlopen

from fontTools import version as fonttools_version
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
VERSION = "3.3.1"
URL = f"https://registry.npmjs.org/@flaticon/flaticon-uicons/-/flaticon-uicons-{VERSION}.tgz"
INTEGRITY = "WN2zuECCdjuGBQrjzN0kpeSygzC5fgF8Q7pDR+FUuGtYWczSdIhIwoD+/fKBEfwqKfNIMZ1WouidevGQ4OJORg=="
# Keep existing semantic app names; one consistent Regular Rounded family.
ICONS = {
    "home": "home-heart", "layers": "layers", "calendar": "calendar",
    "message-circle": "comment-dots", "user": "user", "bell": "bell",
    "help-circle": "interrogation", "alert-circle": "exclamation",
    "info": "info", "clock": "clock", "map-pin": "marker",
    "file-text": "clipboard-prescription", "heart": "heart",
    "activity": "pulse", "shield": "shield-check", "lock": "lock",
    "database": "database", "refresh-cw": "refresh", "wifi-off": "wifi-slash",
    "arrow-right": "arrow-right", "arrow-up": "arrow-up",
    "arrow-up-right": "arrow-up-right", "chevron-right": "angle-right",
    "check": "check", "check-circle": "check-circle", "x": "cross-small", "inbox": "inbox",
}


def main():
    cache = ROOT / "tools/asset-cache" / f"flaticon-uicons-{VERSION}.tgz"
    if not cache.exists():
        cache.parent.mkdir(parents=True, exist_ok=True)
        with urlopen(URL, timeout=60) as response:
            cache.write_bytes(response.read())
    archive = cache.read_bytes()
    assert base64.b64encode(hashlib.sha512(archive).digest()).decode() == INTEGRITY, "Archive integrity mismatch"
    destination = ROOT / "mobile/assets/icons/flaticon"
    destination.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(archive)) as package:
        # Read named members directly; never extract arbitrary archive paths.
        css = package.extractfile("package/css/regular/rounded.css").read().decode()
        font_path = re.search(r"src:url\(\.\./([^()]+\.woff2)\)", css)[1]
        font = TTFont(io.BytesIO(package.extractfile("package/css/" + font_path).read()))
        license_text = package.extractfile("package/LICENSE").read()
    assert font["head"].unitsPerEm == 300 and font["hhea"].ascent == 300 and font["hhea"].descent == 0
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    paths, manifest = {}, []
    for semantic, slug in ICONS.items():
        match = re.search(r'\.fi-rr-' + re.escape(slug) + r':before\{content:"\\([a-f0-9]+)"', css)
        assert match, f"Missing official icon: {slug}"
        pen = SVGPathPen(glyphs)
        glyphs[cmap[int(match[1], 16)]].draw(pen)
        outline = pen.getCommands()
        assert outline, f"Empty outline: {slug}"
        paths[semantic] = outline
        svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="-1 -1 302 302" fill="currentColor">'
               f'<g transform="translate(0 300) scale(1 -1)"><path d="{outline}"/></g></svg>\n')
        asset = f"{slug}.svg"
        (destination / asset).write_bytes(svg.encode("utf-8"))
        manifest.append({"appName": semantic, "flaticonName": f"fi-rr-{slug}", "asset": asset,
                         "sha256": hashlib.sha256(svg.encode()).hexdigest()})
    (destination / "LICENSE.txt").write_bytes(license_text)
    (destination / "manifest.json").write_text(json.dumps({
        "sourcePage": "https://www.flaticon.com/icon-fonts-most-downloaded",
        "officialInstructions": "https://www.flaticon.com/uicons/get-started",
        "package": "@flaticon/flaticon-uicons", "version": VERSION, "archive": URL,
        "archiveIntegrity": "sha512-" + INTEGRITY, "style": "Regular Rounded",
        "conversion": "Original WOFF2 glyph outlines exported as SVG with fontTools " + fonttools_version,
        "attribution": "Uicons by Flaticon", "attributionUrl": "https://www.flaticon.com/uicons",
        "icons": manifest,
    }, indent=2) + "\n", encoding="utf-8", newline="\n")
    (ROOT / "mobile/src/flaticon-paths.ts").write_text(
        "// Generated by scripts/import-flaticon.py; Uicons by Flaticon.\n"
        "// See assets/icons/flaticon/LICENSE.txt and manifest.json.\n"
        "export const flaticonPaths = " + json.dumps(paths, indent=2) + " as const;\n"
        "export type FlaticonName = keyof typeof flaticonPaths;\n", encoding="utf-8", newline="\n")
    print(f"Imported {len(paths)} local Flaticon SVG icons; original outlines, Regular Rounded.")


if __name__ == "__main__":
    main()
